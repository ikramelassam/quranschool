# Découpage des 60 hizb du Coran en 4 quarts (رُبع الحزب / rub' al-hizb),
# soit 240 quarts au total — LE découpage textuel universel du Coran,
# présent dans la marge de la quasi-totalité des Mushaf imprimés.
#
# HIZB_QUARTERS[h-1] est la liste des 4 quarts du hizb h. Chaque quart est
# ((sourate_debut, ayah_debut), (sourate_fin, ayah_fin)) — décompte حفص عن
# عاصم (cohérent avec SOURATES ci-dessus). Un quart peut chevaucher 2
# sourates consécutives (ex: hizb 45, quart 2 = 36:60 -> 37:21).
#
# Source: numéro de quart (rub_el_hizb, 1-240) de chaque verset, obtenu
# depuis l'API officielle Quran.com (https://api.quran.com/api/v4/verses/by_rub/{n},
# texte Uthmani / King Fahd Complex — même référentiel que Quran.com). Les
# limites ont été vérifiées par un double contrôle: (1) interrogation directe
# de l'API pour 20 quarts (hizb 1, 2, 30, 59, 60) et (2) recoupement avec un
# second jeu de données indépendant (malekverse/quran-dataset, champ
# hizb_quarter, github.com/malekverse/quran-dataset) sur les 6236 versets —
# les deux sources concordent à 100%, et les 240 quarts s'enchaînent sans
# trou ni chevauchement, du verset 1:1 au dernier verset 114:6.
#
# NOTE: contrairement aux quarts, la subdivision en 8 "أثمان" (huitièmes)
# évoquée pour certains Mushaf (ex: رواية ورش المُثمَّن au Maghreb) n'est PAS
# un découpage universel avec une source publique vérifiable — elle n'a donc
# pas été encodée ici. Le quart (1/4) est la plus petite unité fiable.
